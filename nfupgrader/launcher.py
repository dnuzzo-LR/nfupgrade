"""launcher.py — launch the local upgrade via the Phase-1 forks and observe it.

We never edit the customer's config; we write a derived config that sources it
and forces PROMPTFORVALIDATE=NO (so confirm_setup does not block on read). The
launch is detached (nf_upgrade backgrounds nf_upgrader and returns); liveness is
discovered by process presence, since we never hold the child pid."""
import os
import subprocess

_MODE_FLAG = {"stage": "-s", "upgrade": "-u"}


def build_launch_argv(nf_upgrade_path, config_path, mode):
    """Return the argv to launch nf_upgrade for the given mode."""
    if mode not in _MODE_FLAG:
        raise ValueError("bad mode: {}".format(mode))
    return [nf_upgrade_path, "-c", config_path, _MODE_FLAG[mode]]


def write_effective_config(user_config, effective_path):
    """Write a derived config that sources the user's config and forces
    PROMPTFORVALIDATE=NO. Returns effective_path. The user's file is untouched."""
    with open(effective_path, "w") as fh:
        fh.write("# generated by nfupgrader; do not edit\n")
        fh.write('. "{}"\n'.format(user_config))
        fh.write("PROMPTFORVALIDATE=NO\n")
    return effective_path


_SHELLS = ("ksh", "ksh93", "sh", "bash")

INSTALL_ACTIONS = {"install": "-i", "resume": "-r", "reset": "-x"}


def is_script_argv(argv, script):
    """True iff argv is `script` itself: exec'd directly, or run by a shell as
    `<shell> [-opts] .../<script> ...` (its #!/usr/bin/ksh shebang). An editor,
    pager or grep that merely names the file is not."""
    if not argv:
        return False
    names = [os.path.basename(a) for a in argv]
    if names[0] == script:
        return True
    if names[0] in _SHELLS:
        for arg, name in zip(argv[1:], names[1:]):
            if arg.startswith("-"):
                if arg == "-c":          # `sh -c "<command string>"` is a wrapper, not the script
                    return False
                continue
            return name == script
    return False


def is_upgrader_argv(argv):
    """True iff argv is nf_upgrader itself. See is_script_argv for the rules."""
    return is_script_argv(argv, "nf_upgrader")


def script_running(host, script):
    """True iff a `script` process is alive on the host. `pgrep -f` only finds
    candidates (any command line containing the name); each candidate's exact
    argv is then read from /proc/<pid>/cmdline."""
    r = host.run(["pgrep", "-f", script])
    if r.rc != 0:
        return False
    for pid in r.out.split():
        c = host.run(["cat", "/proc/{}/cmdline".format(pid)])
        if c.rc == 0 and is_script_argv([a for a in c.out.split("\0") if a], script):
            return True
    return False


def upgrader_running(host):
    """True iff an nf_upgrader process is alive on the host."""
    return script_running(host, "nf_upgrader")


def installer_running(host):
    """True iff an nf_install process is alive on the host."""
    return script_running(host, "nf_install")


def patcher_running(host):
    """True iff an nf_patch process is alive on the host."""
    return script_running(host, "nf_patch")


def anything_running(host):
    """True iff nf_upgrader, nf_install or nf_patch is alive on the host."""
    return upgrader_running(host) or installer_running(host) or patcher_running(host)


def build_patch_argv(nf_patch_path, rpm_path, logdir, web_tar=None):
    """Return the argv to launch nf_patch for one patch rpm, plus -w <tar> to
    install the matching web GUI tar after it."""
    argv = [nf_patch_path, "-f", rpm_path, "-l", logdir]
    if web_tar:
        argv += ["-w", web_tar]
    return argv


def build_install_argv(nf_install_path, config_path, action):
    """Return the argv to launch nf_install for the given action."""
    if action not in INSTALL_ACTIONS:
        raise ValueError("bad action: {}".format(action))
    return [nf_install_path, "-c", config_path, INSTALL_ACTIONS[action]]


def launch(nf_upgrade_path, config_path, mode, cwd=None, env=None):
    """Launch nf_upgrade detached. Returns the Popen (which exits quickly, as
    nf_upgrade backgrounds nf_upgrader). Progress is tracked via the state file
    and upgrader_running(), not this handle. env adds variables to the
    inherited environment (a resumed upgrade's APP_WAS_RUNNING)."""
    argv = build_launch_argv(nf_upgrade_path, config_path, mode)
    full_env = None
    if env:
        full_env = dict(os.environ)
        full_env.update(env)
    return subprocess.Popen(
        argv, cwd=cwd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        start_new_session=True, env=full_env,
    )


def launch_install(nf_install_path, config_path, action, cwd=None):
    """Launch nf_install detached. Returns the Popen, exactly like launch()."""
    argv = build_install_argv(nf_install_path, config_path, action)
    return subprocess.Popen(
        argv, cwd=cwd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        start_new_session=True,
    )


def launch_patch(nf_patch_path, rpm_path, logdir, web_tar=None):
    """Launch nf_patch detached. nf_patch runs in the foreground, so the
    returned Popen's pid is nf_patch's own (its trace is patch_inc_<host>.<pid>)."""
    argv = build_patch_argv(nf_patch_path, rpm_path, logdir, web_tar)
    return subprocess.Popen(
        argv, cwd=None, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
